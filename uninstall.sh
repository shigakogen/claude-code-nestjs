#!/usr/bin/env bash
#
# Remove the claude-code-nestjs kit from a repo.
#
#   ./uninstall.sh [TARGET_REPO] [--yes]
#
# Removes only files this kit installs. Leaves your own CLAUDE.md content alone.
set -euo pipefail

TARGET="."; YES=0
while [ $# -gt 0 ]; do
  case "$1" in
    --yes|-y) YES=1 ;;
    -*) echo "Unknown option: $1" >&2; exit 2 ;;
    *) TARGET="$1" ;;
  esac
  shift
done
[ -d "$TARGET" ] || { echo "No such directory: $TARGET" >&2; exit 1; }
TARGET="$(cd "$TARGET" && pwd)"

echo "This will remove from $TARGET:"
echo "  .claude/  (agents, rules, skills, hooks, commands, settings)"
echo "  .mcp.json  .env.mcp.example"
echo "  the '@.claude/CLAUDE.md' import line in CLAUDE.md, if present"
echo
echo "It will NOT delete: your CLAUDE.md content, SERVICE_MAP.md, .env.mcp, .gitignore entries."

if [ "$YES" -eq 0 ]; then
  printf 'Continue? [y/N] '
  read -r ans
  case "$ans" in y|Y|yes|YES) ;; *) echo "Aborted."; exit 0 ;; esac
fi

if [ -f "$TARGET/.claude/settings.local.json" ]; then
  cp "$TARGET/.claude/settings.local.json" "$TARGET/.claude-settings.local.json.bak"
  echo "Backed up settings.local.json -> .claude-settings.local.json.bak"
fi

rm -rf "$TARGET/.claude"
rm -f  "$TARGET/.mcp.json" "$TARGET/.env.mcp.example"

if [ -f "$TARGET/CLAUDE.md" ] && grep -q '@\.claude/CLAUDE\.md' "$TARGET/CLAUDE.md"; then
  # portable in-place edit (GNU and BSD sed)
  tmp="$(mktemp)"
  grep -v '^@\.claude/CLAUDE\.md$' "$TARGET/CLAUDE.md" > "$tmp"
  mv "$tmp" "$TARGET/CLAUDE.md"
  echo "Removed the import line from CLAUDE.md"
fi

echo "Done. If CLAUDE.md was generated by this kit and you no longer want it, delete it manually."
